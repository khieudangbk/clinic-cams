-- SC7: email log, reminder bookkeeping and the reminder_hours setting.

CREATE TABLE cams_email_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES cams_appointments(id),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('confirm', 'reminder')),
    recipient VARCHAR(150) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL CHECK (status IN ('sent', 'skipped', 'failed', 'disabled')),
    error VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_cams_email_log_appointment ON cams_email_log(appointment_id);

-- Set when a reminder has been handled; reset to NULL when the appointment is rescheduled.
ALTER TABLE cams_appointments ADD COLUMN reminder_sent_at TIMESTAMPTZ NULL;

INSERT INTO cams_settings (setting_key, setting_value) VALUES ('reminder_hours', 24)
ON CONFLICT (setting_key) DO NOTHING;
