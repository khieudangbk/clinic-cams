-- CAMS booking domain: specialties, staff/patients, schedules, slots, appointments, leaves,
-- audit trail and sessions. Mirrors app.py's SQLite SCHEMA, translated to PostgreSQL.

CREATE TABLE cams_specialties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_cams_specialties_name UNIQUE (name)
);

CREATE TABLE cams_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150),
    password_hash VARCHAR(255),
    role VARCHAR(20) NOT NULL CHECK (role IN ('patient', 'receptionist', 'doctor', 'manager')),
    phone VARCHAR(20) NOT NULL DEFAULT '',
    specialty_id BIGINT REFERENCES cams_specialties(id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_cams_users_email UNIQUE (email)
);

CREATE TABLE cams_schedules (
    doctor_id BIGINT PRIMARY KEY REFERENCES cams_users(id),
    weekdays VARCHAR(20) NOT NULL DEFAULT '0,1,2,3,4,5',
    start_time VARCHAR(5) NOT NULL DEFAULT '07:00',
    end_time VARCHAR(5) NOT NULL DEFAULT '17:00'
);

CREATE TABLE cams_settings (
    setting_key VARCHAR(50) PRIMARY KEY,
    setting_value INTEGER NOT NULL
);

INSERT INTO cams_settings (setting_key, setting_value) VALUES
    ('slot_minutes', 30),
    ('cutoff_hours', 2),
    ('max_reschedules', 2),
    ('advance_days', 30),
    ('max_active', 3);

CREATE TABLE cams_leaves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES cams_users(id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(300) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES cams_users(id)
);

CREATE TABLE cams_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES cams_users(id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_cams_slots_doctor_start UNIQUE (doctor_id, starts_at),
    CONSTRAINT ck_cams_slots_order CHECK (ends_at > starts_at)
);

CREATE TABLE cams_appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES cams_users(id),
    slot_id BIGINT NOT NULL REFERENCES cams_slots(id),
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('online', 'staff')),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('pending', 'confirmed', 'arrived', 'completed', 'cancelled', 'noshow')),
    reason VARCHAR(500) NOT NULL,
    reschedule_count INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT NOT NULL REFERENCES cams_users(id),
    created_at TIMESTAMPTZ NOT NULL,
    booking_details TEXT NOT NULL DEFAULT '',
    patient_name_override VARCHAR(100) NOT NULL DEFAULT '',
    patient_phone_override VARCHAR(20) NOT NULL DEFAULT ''
);

-- At most one pending/confirmed/arrived appointment may hold a given slot at a time.
CREATE UNIQUE INDEX one_active_appointment_per_slot ON cams_appointments(slot_id)
    WHERE status IN ('pending', 'confirmed', 'arrived');
CREATE INDEX idx_cams_appointments_patient ON cams_appointments(patient_id);

CREATE TABLE cams_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL REFERENCES cams_appointments(id),
    actor_id BIGINT NOT NULL REFERENCES cams_users(id),
    action VARCHAR(30) NOT NULL,
    before_json TEXT NOT NULL,
    after_json TEXT NOT NULL,
    reason VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE cams_sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES cams_users(id),
    csrf VARCHAR(64) NOT NULL,
    expires TIMESTAMPTZ NOT NULL
);
